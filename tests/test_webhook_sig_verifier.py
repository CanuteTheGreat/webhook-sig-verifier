"""End-to-end tests for webhook_sig_verifier.py.

Signatures are produced or checked by the providers' own code wherever it
exists, so the tests prove the tool agrees with what the real services and
their official SDKs do, not with a re-implementation of itself:
  - GitHub: the worked example from GitHub's "Validating webhook deliveries" docs
  - Stripe: headers accepted by the official `stripe` library's verify_header
  - Slack: signatures generated by the official `slack_sdk` SignatureVerifier
  - Twilio: signatures computed by the official `twilio` RequestValidator
  - Standard Webhooks: the spec's published example, plus signatures from the official
    `standardwebhooks` library (Python >= 3.9); Ed25519 signatures made with `cryptography`
The tool always runs unmodified as a subprocess (ci/setup.sh installs the SDKs).
"""
import base64
import datetime
import hashlib
import hmac
import json
import os
import subprocess
import sys
import tempfile
import time
import unittest

import stripe
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from slack_sdk.signature import SignatureVerifier
from twilio.request_validator import RequestValidator

try:
    from standardwebhooks.webhooks import Webhook as StandardWebhook
except ImportError:  # only installed on Python >= 3.9 (the library's minimum)
    StandardWebhook = None

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.join(os.path.dirname(HERE), "webhook_sig_verifier.py")
STRIPE_SIG_ERROR = getattr(stripe, "SignatureVerificationError", None) or stripe.error.SignatureVerificationError
BODY = b'{"id":"evt_1","object":"event","type":"payment_intent.succeeded","data":{"amount":420}}'


def run(*args, stdin=None):
    return subprocess.run([sys.executable, TOOL] + list(args), capture_output=True, input=stdin, timeout=60)


def out(p):
    return p.stdout.decode() + p.stderr.decode()


class PayloadFile:
    def __enter__(self):
        fd, self.path = tempfile.mkstemp()
        os.write(fd, BODY)
        os.close(fd)
        return self.path

    def __exit__(self, *a):
        os.unlink(self.path)


class TestGitHub(unittest.TestCase):
    # https://docs.github.com/en/webhooks/using-webhooks/validating-webhook-deliveries
    SECRET, PAYLOAD = "It's a Secret to Everybody", "Hello, World!"
    SIG = "sha256=757107ea0eb2509fc211221cce984b8a37570b6d7586c22c46f4379c8b043e17"

    def test_documented_example_valid(self):
        p = run("--scheme", "github", "--secret", self.SECRET, "--payload", self.PAYLOAD, "--signature", self.SIG)
        self.assertEqual(p.returncode, 0, out(p))
        self.assertTrue(p.stdout.startswith(b"VALID"), out(p))

    def test_uppercase_hex_still_valid(self):
        p = run("--scheme", "github", "--secret", self.SECRET, "--payload", self.PAYLOAD,
                "--signature", "sha256=" + self.SIG.split("=")[1].upper())
        self.assertEqual(p.returncode, 0, out(p))

    def test_legacy_sha1(self):
        sig = "sha1=" + hmac.new(self.SECRET.encode(), self.PAYLOAD.encode(), hashlib.sha1).hexdigest()
        p = run("--scheme", "github", "--secret", self.SECRET, "--payload", self.PAYLOAD, "--signature", sig)
        self.assertEqual(p.returncode, 0, out(p))

    def test_wrong_secret_or_changed_body_invalid(self):
        for secret, payload in (("wrong", self.PAYLOAD), (self.SECRET, "Hello, World! ")):
            p = run("--scheme", "github", "--secret", secret, "--payload", payload, "--signature", self.SIG)
            self.assertEqual(p.returncode, 1, out(p))
            self.assertTrue(p.stdout.startswith(b"INVALID"), out(p))

    def test_malformed_and_unsupported(self):
        p = run("--scheme", "github", "--secret", "s", "--payload", "x", "--signature", "deadbeef")
        self.assertEqual(p.returncode, 1)
        self.assertIn("malformed signature", out(p))
        p = run("--scheme", "github", "--secret", "s", "--payload", "x", "--signature", "md5=abc")
        self.assertEqual(p.returncode, 1)
        self.assertIn("unsupported algo 'md5'", out(p))


class TestStripe(unittest.TestCase):
    SECRET = "whsec_test_errant_solutions_ci"

    def header(self, ts, *secrets, extra=""):
        v1 = ",".join("v1=" + hmac.new(s.encode(), f"{ts}.".encode() + BODY, hashlib.sha256).hexdigest()
                      for s in secrets)
        return f"t={ts},{v1}{extra}"

    def stripe_accepts(self, header, tolerance=300):
        stripe.WebhookSignature.verify_header(BODY.decode(), header, self.SECRET, tolerance)

    def test_fresh_signature_valid_and_matches_stripe_library(self):
        h = self.header(int(time.time()), self.SECRET, extra=",v0=" + "0" * 64)
        self.stripe_accepts(h)  # raises if Stripe's own library disagrees
        with PayloadFile() as f:
            p = run("--scheme", "stripe", "--secret", self.SECRET, "--payload-file", f, "--signature", h)
        self.assertEqual(p.returncode, 0, out(p))
        self.assertNotIn("WARNING", out(p))

    def test_secret_roll_multiple_v1_values(self):
        # During a secret roll Stripe signs with the old AND new secret: one header, two v1= values.
        for order in (("whsec_old", self.SECRET), (self.SECRET, "whsec_old")):
            h = self.header(int(time.time()), *order)
            self.stripe_accepts(h)
            with PayloadFile() as f:
                p = run("--scheme", "stripe", "--secret", self.SECRET, "--payload-file", f, "--signature", h)
            self.assertEqual(p.returncode, 0, (order, out(p)))

    def test_stale_timestamp_warns_and_tolerance_option(self):
        ts = int(time.time()) - 3600
        h = self.header(ts, self.SECRET)
        with self.assertRaises(STRIPE_SIG_ERROR):
            self.stripe_accepts(h)  # Stripe rejects it as a replay...
        with PayloadFile() as f:
            p = run("--scheme", "stripe", "--secret", self.SECRET, "--payload-file", f, "--signature", h)
            self.assertIn("WARNING: timestamp is", out(p))  # ...and the tool says so
            self.assertIn("tolerance 300s", out(p))
            p = run("--scheme", "stripe", "--secret", self.SECRET, "--payload-file", f, "--signature", h,
                    "--tolerance", "7200")
            self.assertNotIn("WARNING", out(p))
            self.assertEqual(p.returncode, 0, out(p))

    def test_wrong_secret_invalid(self):
        h = self.header(int(time.time()), "whsec_someone_else")
        with PayloadFile() as f:
            p = run("--scheme", "stripe", "--secret", self.SECRET, "--payload-file", f, "--signature", h)
        self.assertEqual(p.returncode, 1, out(p))

    def test_malformed_header_and_bad_timestamp(self):
        p = run("--scheme", "stripe", "--secret", self.SECRET, "--payload", "x", "--signature", "v1=abc")
        self.assertEqual(p.returncode, 1)
        self.assertIn("malformed signature", out(p))
        p = run("--scheme", "stripe", "--secret", self.SECRET, "--payload", "x", "--signature", "t=soon,v1=abc")
        self.assertIn("timestamp is not a valid integer", out(p))


class TestSlack(unittest.TestCase):
    SECRET = "8f742231b10e8888abcd99yyyzzz85a5"

    def sig(self, ts, body=BODY):
        return SignatureVerifier(self.SECRET).generate_signature(timestamp=str(ts), body=body.decode())

    def test_valid_signature_from_slack_sdk(self):
        ts = int(time.time())
        sig = self.sig(ts)
        self.assertTrue(SignatureVerifier(self.SECRET).is_valid(BODY.decode(), str(ts), sig))
        with PayloadFile() as f:
            p = run("--scheme", "slack", "--secret", self.SECRET, "--payload-file", f, "--signature", sig,
                    "--timestamp", str(ts))
        self.assertEqual(p.returncode, 0, out(p))
        self.assertNotIn("WARNING", out(p))

    def test_stale_timestamp_and_tolerance(self):
        ts = int(time.time()) - 900
        sig = self.sig(ts)
        self.assertFalse(SignatureVerifier(self.SECRET).is_valid(BODY.decode(), str(ts), sig))
        with PayloadFile() as f:
            p = run("--scheme", "slack", "--secret", self.SECRET, "--payload-file", f, "--signature", sig,
                    "--timestamp", str(ts))
            self.assertIn("WARNING: timestamp is", out(p))
            p = run("--scheme", "slack", "--secret", self.SECRET, "--payload-file", f, "--signature", sig,
                    "--timestamp", str(ts), "--tolerance", "1000")
            self.assertNotIn("WARNING", out(p))

    def test_timestamp_is_part_of_the_signature(self):
        ts = int(time.time())
        with PayloadFile() as f:
            p = run("--scheme", "slack", "--secret", self.SECRET, "--payload-file", f, "--signature", self.sig(ts),
                    "--timestamp", str(ts + 1))
        self.assertEqual(p.returncode, 1, out(p))

    def test_missing_timestamp_is_usage_error(self):
        p = run("--scheme", "slack", "--secret", self.SECRET, "--payload", "x", "--signature", "v0=abc")
        self.assertEqual(p.returncode, 2, out(p))
        self.assertIn("requires --timestamp", out(p))

    def test_malformed_signature(self):
        p = run("--scheme", "slack", "--secret", self.SECRET, "--payload", "x", "--signature", "abc",
                "--timestamp", str(int(time.time())))
        self.assertEqual(p.returncode, 1)
        self.assertIn("expected 'v0=<hex>'", out(p))


class TestGenericAndInput(unittest.TestCase):
    def test_generic_sha256_and_sha1(self):
        for scheme, mod in (("generic-sha256", hashlib.sha256), ("generic-sha1", hashlib.sha1)):
            sig = hmac.new(b"k", BODY, mod).hexdigest()
            with PayloadFile() as f:
                p = run("--scheme", scheme, "--secret", "k", "--payload-file", f, "--signature", sig)
                self.assertEqual(p.returncode, 0, out(p))
                p = run("--scheme", scheme, "--secret", "k2", "--payload-file", f, "--signature", sig)
                self.assertEqual(p.returncode, 1, out(p))

    def test_payload_from_stdin_is_exact_bytes(self):
        sig = hmac.new(b"k", BODY + b"\n", hashlib.sha256).hexdigest()
        p = run("--scheme", "generic-sha256", "--secret", "k", "--signature", sig, stdin=BODY + b"\n")
        self.assertEqual(p.returncode, 0, out(p))
        p = run("--scheme", "generic-sha256", "--secret", "k", "--signature", sig, stdin=BODY)
        self.assertEqual(p.returncode, 1, out(p))  # one trailing newline is a different body

    def test_payload_file_keeps_exact_bytes(self):
        body = "caf\u00e9\r\n".encode("utf-8")
        sig = hmac.new(b"k", body, hashlib.sha256).hexdigest()
        fd, path = tempfile.mkstemp()
        os.write(fd, body)
        os.close(fd)
        try:
            p = run("--scheme", "generic-sha256", "--secret", "k", "--payload-file", path, "--signature", sig)
        finally:
            os.unlink(path)
        self.assertEqual(p.returncode, 0, out(p))

    def test_usage_errors_exit_2(self):
        cases = [
            ("--secret", "k", "--signature", "x", "--payload", "y"),                       # no --scheme
            ("--scheme", "nope", "--secret", "k", "--signature", "x", "--payload", "y"),   # bad scheme
            ("--scheme", "github", "--signature", "x", "--payload", "y"),                  # no --secret
            ("--scheme", "github", "--secret", "k", "--signature", "x", "--payload", "y",
             "--payload-file", "/etc/hostname"),                                            # both payloads
            ("--scheme", "github", "--secret", "k", "--signature", "x",
             "--payload-file", "/nonexistent/body.json"),                                   # unreadable file
        ]
        for c in cases:
            p = run(*c)
            self.assertEqual(p.returncode, 2, (c, out(p)))
            self.assertNotIn("Traceback", out(p))


class TestStandardWebhooks(unittest.TestCase):
    # Example from the Standard Webhooks spec / Svix docs
    SECRET = "whsec_MfKQ9r8GKYqrTwjUPD8ILPZIo2LaLaSw"
    MSG_ID, TS, BODY = "msg_p5jXN8AQM9LWM0D4loKWxJek", "1614265330", '{"test": 2432232314}'
    SIG = "v1,g0hM9SsE+OTPJTGt/tmIKtSyZlE3uFJELVlNIOLJ1OE="

    def sw(self, *extra, secret=None, sig=None, msg_id=None, ts=None, body=None):
        return run("--scheme", "standard-webhooks", "--secret", secret or self.SECRET, "--webhook-id", msg_id or self.MSG_ID,
                   "--timestamp", ts or self.TS, "--payload", body if body is not None else self.BODY,
                   "--signature", sig or self.SIG, "--tolerance", "999999999", *extra)

    def test_published_example(self):
        p = self.sw()
        self.assertEqual(p.returncode, 0, out(p))
        self.assertIn("computed " + self.SIG, out(p))
        self.assertEqual(self.sw(body='{"test": 2432232315}').returncode, 1)
        self.assertEqual(self.sw(msg_id="msg_other").returncode, 1)
        # several space-separated signatures (key rotation): any match is valid
        self.assertEqual(self.sw(sig="v1,bm9wZQ== " + self.SIG).returncode, 0)

    def test_matches_official_library(self):
        if StandardWebhook is None:
            self.assertLess(sys.version_info, (3, 9))  # library unavailable here; the published example covers it
            self.assertEqual(self.sw().returncode, 0)
            return
        now = datetime.datetime.now(tz=datetime.timezone.utc)
        sig = StandardWebhook(self.SECRET).sign("msg_live", now, BODY.decode())
        StandardWebhook(self.SECRET).verify(BODY, {"webhook-id": "msg_live", "webhook-signature": sig,
                                                   "webhook-timestamp": str(int(now.timestamp()))})
        p = run("--scheme", "standard-webhooks", "--secret", self.SECRET, "--webhook-id", "msg_live",
                "--timestamp", str(int(now.timestamp())), "--payload", BODY.decode(), "--signature", sig)
        self.assertEqual(p.returncode, 0, out(p))
        self.assertNotIn("WARNING", out(p))

    def test_ed25519_v1a(self):
        key = Ed25519PrivateKey.generate()
        pub = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        whpk = "whpk_" + base64.b64encode(pub).decode()
        ts = str(int(time.time()))
        sig = "v1a," + base64.b64encode(key.sign(("msg_ed.%s." % ts).encode() + BODY)).decode()
        args = ("--scheme", "standard-webhooks", "--secret", whpk, "--webhook-id", "msg_ed", "--timestamp", ts)
        p = run(*args, "--payload", BODY.decode(), "--signature", sig)
        self.assertEqual(p.returncode, 0, out(p))
        self.assertIn("Ed25519 (v1a) signature verified", out(p))
        p = run(*args, "--payload", BODY.decode() + " ", "--signature", sig)
        self.assertEqual(p.returncode, 1, out(p))
        other = Ed25519PrivateKey.generate().public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        p = run("--scheme", "standard-webhooks", "--secret", "whpk_" + base64.b64encode(other).decode(),
                "--webhook-id", "msg_ed", "--timestamp", ts, "--payload", BODY.decode(), "--signature", sig)
        self.assertEqual(p.returncode, 1, out(p))

    def test_stale_and_usage(self):
        p = self.sw("--tolerance", "300")
        self.assertIn("WARNING: timestamp is", out(p))
        p = run("--scheme", "standard-webhooks", "--secret", self.SECRET, "--payload", "x", "--signature", self.SIG)
        self.assertEqual(p.returncode, 2)
        self.assertEqual(self.sw(sig="garbage").returncode, 1)
        self.assertEqual(self.sw(secret="whsec_!!!notbase64").returncode, 1)


class TestBase64Providers(unittest.TestCase):
    def test_shopify(self):
        sig = base64.b64encode(hmac.new(b"shpss_k", BODY, hashlib.sha256).digest()).decode()
        with PayloadFile() as f:
            self.assertEqual(run("--scheme", "shopify", "--secret", "shpss_k", "--payload-file", f, "--signature", sig).returncode, 0)
            self.assertEqual(run("--scheme", "shopify", "--secret", "other", "--payload-file", f, "--signature", sig).returncode, 1)
            self.assertEqual(run("--scheme", "shopify", "--secret", "shpss_k", "--payload-file", f, "--signature", "%%%").returncode, 1)

    def test_square(self):
        url = "https://example.com/square/webhook"
        sig = base64.b64encode(hmac.new(b"sq_key", url.encode() + BODY, hashlib.sha256).digest()).decode()
        with PayloadFile() as f:
            self.assertEqual(run("--scheme", "square", "--secret", "sq_key", "--url", url, "--payload-file", f,
                                 "--signature", sig).returncode, 0)
            self.assertEqual(run("--scheme", "square", "--secret", "sq_key", "--url", url + "/x", "--payload-file", f,
                                 "--signature", sig).returncode, 1)
            self.assertEqual(run("--scheme", "square", "--secret", "sq_key", "--payload-file", f, "--signature", sig).returncode, 2)

    def test_twilio_form_and_json_bodies_match_official_validator(self):
        token, url = "12345", "https://mycompany.com/myapp.php?foo=1&bar=2"
        params = {"CallSid": "CA1234567890ABCDE", "Caller": "+12349013030", "Digits": "1234", "From": "+12349013030"}
        v = RequestValidator(token)
        sig = v.compute_signature(url, params)
        body = "&".join("%s=%s" % (k, val.replace("+", "%2B")) for k, val in params.items())
        p = run("--scheme", "twilio", "--secret", token, "--url", url, "--payload", body, "--signature", sig)
        self.assertEqual(p.returncode, 0, out(p))
        self.assertEqual(run("--scheme", "twilio", "--secret", "wrong", "--url", url, "--payload", body,
                             "--signature", sig).returncode, 1)
        jbody = '{"property": "value", "boolean": true}'
        jurl = "https://mycompany.com/myapp.php?bodySHA256=" + hashlib.sha256(jbody.encode()).hexdigest()
        jsig = v.compute_signature(jurl, {})
        self.assertTrue(v.validate(jurl, jbody, jsig))
        p = run("--scheme", "twilio", "--secret", token, "--url", jurl, "--payload", jbody, "--signature", jsig)
        self.assertEqual(p.returncode, 0, out(p))
        self.assertIn("bodySHA256 matches", out(p))
        p = run("--scheme", "twilio", "--secret", token, "--url", jurl, "--payload", jbody + " ", "--signature", jsig)
        self.assertEqual(p.returncode, 1, out(p))
        self.assertIn("DOES NOT match", out(p))

    def test_zoom(self):
        ts = str(int(time.time()))
        sig = "v0=" + hmac.new(b"zoomtoken", ("v0:%s:" % ts).encode() + BODY, hashlib.sha256).hexdigest()
        with PayloadFile() as f:
            self.assertEqual(run("--scheme", "zoom", "--secret", "zoomtoken", "--payload-file", f, "--signature", sig,
                                 "--timestamp", ts).returncode, 0)
            self.assertEqual(run("--scheme", "zoom", "--secret", "zoomtoken", "--payload-file", f, "--signature", sig).returncode, 2)

    def test_generic_base64_and_sha512(self):
        for scheme, mod in (("generic-sha256", hashlib.sha256), ("generic-sha512", hashlib.sha512)):
            sig = base64.b64encode(hmac.new(b"k", BODY, mod).digest()).decode()
            with PayloadFile() as f:
                p = run("--scheme", scheme, "--encoding", "base64", "--secret", "k", "--payload-file", f, "--signature", sig)
                self.assertEqual(p.returncode, 0, out(p))
                p = run("--scheme", scheme, "--secret", "k", "--payload-file", f, "--signature", sig)
                self.assertEqual(p.returncode, 1, out(p))  # hex expected by default


class TestJsonAndVersion(unittest.TestCase):
    def test_json(self):
        sig = hmac.new(b"k", BODY, hashlib.sha256).hexdigest()
        p = run("--scheme", "generic-sha256", "--secret", "k", "--signature", sig, "--json", stdin=BODY)
        self.assertEqual(p.returncode, 0)
        d = json.loads(p.stdout)
        self.assertEqual((d["valid"], d["scheme"], d["payload_bytes"]), (True, "generic-sha256", len(BODY)))
        self.assertEqual(d["notes"], ["computed sha256=" + sig])
        p = run("--scheme", "generic-sha256", "--secret", "x", "--signature", sig, "--json", stdin=BODY)
        self.assertEqual(p.returncode, 1)
        self.assertFalse(json.loads(p.stdout)["valid"])

    def test_version(self):
        p = run("--version")
        self.assertRegex(p.stdout.decode(), r"^webhook-sig-verifier \d+\.\d+\.\d+$")


if __name__ == "__main__":
    unittest.main()
